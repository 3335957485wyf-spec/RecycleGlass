def draw_icon(d, key: str, size: float, cx: float, cy: float, color,
              width: float, rotate: float = 0.0) -> None:
    """Stroke a baked Lucide icon centred on (cx, cy), 24-unit grid.

    ``rotate`` is in degrees, clockwise — used to animate the disclosure
    chevron instead of swapping between two sprites.
    """
    ent = ICONS.get(key)
    if ent is None:
        return
    subs, closed = ent
    u = size / 24.0
    w = max(1, int(round(width)))
    r = w / 2.0
    ca = cb = 1.0
    if rotate:
        import math
        rad = math.radians(rotate)
        ca, cb = math.cos(rad), math.sin(rad)
    for pts, is_closed in zip(subs, closed):
        if rotate:
            xy = []
            for x, y in zip(pts[0::2], pts[1::2]):
                dx = (x - 12.0) * u
                dy = (y - 12.0) * u
                xy.append((cx + dx * ca - dy * cb, cy + dx * cb + dy * ca))
        else:
            xy = [(cx + (x - 12.0) * u, cy + (y - 12.0) * u)
                  for x, y in zip(pts[0::2], pts[1::2])]
        if len(xy) < 2:
            if xy:
                x, y = xy[0]
                d.ellipse((x - r, y - r, x + r, y + r), fill=color)
            continue
        if is_closed:
            xy.append(xy[0])
        d.line(xy, fill=color, width=w, joint="curve")
        caps = [xy[0]] if is_closed else [xy[0], xy[-1]]
        for x, y in caps:
            d.ellipse((x - r, y - r, x + r, y + r), fill=color)

